"use client";

import { useState, useEffect, useRef, useCallback } from "react";
import { useRouter } from "next/navigation";
import { AcViewer } from "./ac-viewer";
import { AcToc } from "./ac-toc";
import { ChatPanel } from "@/components/chat";
import { useChatStore, useUIStore } from "@/store";
import { usePanelResize } from "@/hooks/use-panel-resize";
import { cn } from "@/lib/utils";
import type { AcFeature, AcVersion, Plan } from "@/types/database";
import {
  Infinity as InfinityIcon,
  FileText,
  X,
  PanelRightClose,
  MessageSquare,
  ArrowRight,
} from "lucide-react";
import Link from "next/link";

interface AcDetailProps {
  projectId: string;
  projectName: string;
  latestAcVersion?: AcVersion;
  allAcVersions?: AcVersion[];
  latestPrdContent?: string;
  conversationId?: string;
  plan?: Plan;
  revisionLimit?: number;
  initialMessages?: Array<{
    id: string;
    role: string;
    content: string;
    created_at: string;
  }>;
}

export function AcDetail({
  projectId,
  projectName,
  latestAcVersion,
  allAcVersions = [],
  latestPrdContent,
  conversationId,
  plan = "free",
  revisionLimit,
  initialMessages = [],
}: AcDetailProps) {
  const router = useRouter();
  const { rightWidth, onStartDragRight, isDraggingRight } = usePanelResize();
  const showToast = useUIStore((s) => s.showToast);
  const setMessages = useChatStore((s) => s.setMessages);
  const isChatOpen = useUIStore((s) => s.isChatPanelOpen);
  const toggleChat = useUIStore((s) => s.toggleChatPanel);

  // Reset and hydrate chat for AC context (separate from PRD chat)
  useEffect(() => {
    const store = useChatStore.getState();
    if (store.activeProjectId !== projectId) {
      store.setActiveProject(projectId);
      setMessages(
        initialMessages.map((m) => ({
          id: m.id,
          role: m.role as "user" | "assistant" | "system",
          content: m.content,
          timestamp: new Date(m.created_at).getTime(),
        })),
      );
    }
    // Reset auto-generate guard on project switch
    hasAutoGenerated.current = false;
  }, [projectId, initialMessages, setMessages]);

  const [isGenerating, setIsGenerating] = useState(false);
  const [streamingContent, setStreamingContent] = useState<string>("");
  const hasAutoGenerated = useRef(false);
  const abortRef = useRef<AbortController | null>(null);

  const parsedFeatures = latestAcVersion?.content || null;

  const handleGenerate = useCallback(async () => {
    if (!latestPrdContent) {
      showToast("PRD belum tersedia. Generate PRD terlebih dahulu.", "error");
      return;
    }
    setIsGenerating(true);
    setStreamingContent("");

    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;

    let gotDoneEvent = false;
    try {
      const response = await fetch("/api/ac/generate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ projectId }),
        signal: controller.signal,
      });
      if (!response.ok) {
        const error = await response.json();
        throw new Error(error.error || "Failed to generate AC");
      }
      const reader = response.body?.getReader();
      if (!reader) throw new Error("No reader available");
      const decoder = new TextDecoder();
      let buffer = "";
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split("\n");
        buffer = lines.pop() || "";
        for (const line of lines) {
          if (line.startsWith("data: ")) {
            try {
              const data = JSON.parse(line.slice(6));
              if (data.type === "delta") {
                setStreamingContent((prev) => prev + data.content);
              } else if (data.type === "done") {
                gotDoneEvent = true;
                router.refresh();
                showToast("Acceptance Criteria berhasil digenerate!", "success");
              } else if (data.type === "error") {
                showToast(data.error || "Gagal generate AC", "error");
              }
            } catch (e) { /* skip */ }
          }
        }
      }
    } catch (error: unknown) {
      if (error instanceof DOMException && error.name === "AbortError") return;
      console.error("Generate AC error:", error);
      const msg = error instanceof Error ? error.message : "Gagal generate AC";
      showToast(msg, "error");
    } finally {
      setIsGenerating(false);
      if (!gotDoneEvent) setStreamingContent("");
    }
  }, [projectId, latestPrdContent, showToast, router]);

  // Auto-generate AC on first visit
  useEffect(() => {
    if (!latestPrdContent || latestAcVersion || hasAutoGenerated.current || isGenerating) return;
    hasAutoGenerated.current = true;
    handleGenerate();
    return () => { abortRef.current?.abort(); };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [latestPrdContent, latestAcVersion, handleGenerate]);

  const handleStepTask = async () => {
    try {
      const res = await fetch(`/api/projects/${projectId}/step`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ step: "task" }),
      });
      if (!res.ok) throw new Error("Failed to update step");
      router.push(`/task/${projectId}`);
    } catch (err) {
      console.error("Step to task failed:", err);
      showToast("Gagal lanjut ke Task.", "error");
    }
  };

  if (!latestPrdContent) {
    return (
      <div className="flex h-dvh items-center justify-center bg-onyx text-snow">
        <div className="text-center">
          <FileText size={64} className="mx-auto mb-4 text-fog" />
          <h2 className="mb-2 text-xl font-[510]">PRD Belum Tersedia</h2>
          <p className="mb-6 text-fog">Generate PRD terlebih dahulu sebelum membuat Acceptance Criteria.</p>
          <Link href={`/prd/${projectId}`} className="btn-primary inline-flex items-center gap-2 rounded-md px-4 py-2">
            <ArrowRight size={16} /> Ke PRD
          </Link>
        </div>
      </div>
    );
  }

  const isStreaming = isGenerating && streamingContent.length > 0;

  return (
    <div className="flex h-dvh overflow-hidden bg-onyx text-snow">
      {/* Left: TOC */}
      <aside className="hidden w-64 shrink-0 overflow-y-auto border-r border-graphite bg-obsidian md:block" style={{ overscrollBehavior: "contain" }}>
        <AcToc features={parsedFeatures || []} className="sticky top-0" />
      </aside>

      {/* Center */}
      <div
        className="flex min-w-0 flex-1 flex-col overflow-hidden"
        style={{ background: "var(--bg-page)" }}
      >
        {/* Topbar */}
        <div className="flex shrink-0 items-center justify-between border-b border-graphite bg-obsidian px-4 py-3" style={{ overscrollBehavior: "none", touchAction: "none" }}>
          <div className="flex items-center gap-3">
            <h1 className="truncate font-inter text-lg font-[510]">AC &mdash; {projectName}</h1>
            {revisionLimit !== undefined && (
              <span className="flex items-center gap-1 rounded bg-charcoal px-2 py-1 text-xs text-fog">
                Revisi: {allAcVersions.length > 0 ? allAcVersions.length - 1 : 0}/
                {revisionLimit === -1 ? <InfinityIcon size={12} /> : revisionLimit}
              </span>
            )}
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={toggleChat}
              className={cn(
                "flex items-center gap-2 rounded px-3 py-1.5 text-sm transition-colors",
                isChatOpen ? "bg-indigo text-white" : "bg-charcoal text-fog hover:bg-white/5 hover:text-snow"
              )}
            >
              {isChatOpen ? <PanelRightClose size={16} /> : <MessageSquare size={16} />}
              <span className="hidden sm:inline">{isChatOpen ? "Tutup Chat" : "Revisi AC"}</span>
            </button>
          </div>
        </div>

        {/* AC Viewer */}
        <div className="flex-1 overflow-y-auto" style={{ overscrollBehavior: "contain" }}>
          <AcViewer
            content={parsedFeatures}
            streamingContent={streamingContent}
            isStreaming={isStreaming}
            projectName={projectName}
            plan={plan}
            className=""
          />
        </div>

        {/* ActionBar */}
        <div className="flex shrink-0 items-center justify-end gap-3 border-t border-graphite bg-obsidian px-4 py-3" style={{ overscrollBehavior: "none", touchAction: "none" }}>
          {isGenerating && (
            <button disabled className="flex items-center gap-2 rounded-md bg-charcoal px-4 py-2 text-sm text-fog">
              <div className="h-4 w-4 animate-spin rounded-full border-2 border-indigo border-t-transparent" />
              Mengenerate AC...
            </button>
          )}
          {!isGenerating && !latestAcVersion && !streamingContent && (
            <button onClick={handleGenerate} className="btn-primary flex items-center gap-2 rounded-md px-4 py-2 text-sm font-[510]">
              Generate AC
            </button>
          )}
          {!isGenerating && (latestAcVersion || streamingContent) && (
            <button onClick={handleStepTask} className="btn-primary flex items-center gap-2 rounded-md px-4 py-2 text-sm font-[510]">
              Lanjut Generate Task
              <ArrowRight size={16} />
            </button>
          )}
        </div>
      </div>

      {/* ═══════════ Right Panel: Desktop Chat ═══════════ */}
      <div
        id="print-hide-chat"
        style={{ width: isChatOpen ? `${rightWidth}px` : "0px", background: "var(--bg-elevated)" }}
        className={cn(
          "group/right-sidebar relative hidden shrink-0 border-l border-graphite print:hidden xl:block",
          !isDraggingRight && "transition-all duration-300",
          !isChatOpen && "overflow-hidden border-none",
        )}
      >
        {isChatOpen && (
          <div
            className="absolute bottom-0 left-[-4px] top-0 z-10 w-2 cursor-col-resize transition-colors hover:bg-indigo/20"
            onMouseDown={onStartDragRight}
          />
        )}
        <div className="h-full w-full" style={{ display: isChatOpen ? 'block' : 'none' }}>
          <div className="flex h-full flex-col overflow-hidden" style={{ overscrollBehavior: "none", touchAction: "none" }}>
            <div className="flex-1 overflow-hidden">
              <ChatPanel
                projectId={projectId}
                conversationId={conversationId}
                className="h-full"
                acMode={true}
                currentAcContent={latestAcVersion?.content ? JSON.stringify(latestAcVersion.content) : ""}
                onStreamContent={setStreamingContent}
                inputDisabled={isGenerating}
                currentPrdContent={latestPrdContent || ""}
                userPlan={plan}
              />
            </div>
          </div>
        </div>
      </div>

      {/* ═══════════ Mobile Chat Overlay ═══════════ */}
      <div className="xl:hidden print:hidden">
        {isChatOpen && (
          <div
            role="dialog"
            aria-modal="true"
            aria-label="Panel chat revisi"
            className="fixed bottom-0 left-0 right-0 z-40 h-[60vh] rounded-t-xl bg-charcoal shadow-[var(--shadow-overlay)]"
          >
            <div className="flex items-center justify-between border-b border-graphite px-4 py-2">
              <span className="text-sm font-[510]">Chat</span>
              <button
                onClick={toggleChat}
                aria-label="Tutup chat"
                className="text-fog hover:text-snow"
              >
                <X size={16} />
              </button>
            </div>
            <div className="h-[calc(60vh-44px)]">
              <ChatPanel
                projectId={projectId}
                conversationId={conversationId}
                className="h-full"
                acMode={true}
                currentAcContent={latestAcVersion?.content ? JSON.stringify(latestAcVersion.content) : ""}
                onStreamContent={setStreamingContent}
                inputDisabled={isGenerating}
                currentPrdContent={latestPrdContent || ""}
                userPlan={plan}
              />
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
